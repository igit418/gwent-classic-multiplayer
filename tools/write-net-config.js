// Writes net-config.js from environment variables (used by the GitHub Pages workflow).
//   TURN_URLS             comma separated TURN addresses
//   TURN_USERNAME         username for TURN_URLS
//   TURN_CREDENTIAL       password for TURN_URLS
//   TURN_CREDENTIALS_URL  URL returning a JSON list of ICE servers (e.g. Metered.ca API)
//   TURN_RELAY_ONLY       "true" forces traffic through TURN
// Usage: node tools/write-net-config.js [output file, default net-config.js]
"use strict";
const fs = require("fs");

const env = name => (process.env[name] || "").trim();
const cfg = {};
const urls = env("TURN_URLS").split(",").map(u => u.trim()).filter(Boolean);
if (urls.length) {
	cfg.turnUrls = urls;
	cfg.turnUsername = env("TURN_USERNAME");
	cfg.turnCredential = env("TURN_CREDENTIAL");
}
if (env("TURN_CREDENTIALS_URL"))
	cfg.credentialsUrl = env("TURN_CREDENTIALS_URL");
if (env("TURN_RELAY_ONLY") === "true")
	cfg.relayOnly = true;

const out = process.argv[2] || "net-config.js";
fs.writeFileSync(out, '"use strict"\n\n// Generated by tools/write-net-config.js\nwindow.GWENT_NET_CONFIG = ' + JSON.stringify(cfg, null, "\t") + ";\n");
console.log("Wrote " + out + " with: " + (Object.keys(cfg).join(", ") || "defaults only"));
